from pathlib import Path

root = Path(__file__).resolve().parent
config_path = root / 'neoperro-config.lua'
config = config_path.read_text()
config = config.replace('-- Configuration only; the main runtime is still to be implemented.',
                        '-- Edit this table and execute neoperro.lua again to apply it.')
config = config.replace('-- Intended filters; neither mode guarantees hits or cancels network lag.',
                        '-- Limits prediction displacement; neither mode guarantees hits or cancels network lag.')
config = config.replace('-- Angular threshold in degrees.', '-- Maximum angle between direct and predicted aim, in degrees.')
config = config.replace('-- Radius in studs for the planned final-point adjustment.', '-- Maximum final-point displacement from the body point, in studs.')
config = config.replace('-- Estimate velocity from timestamped position samples.',
                        '-- Fit velocity to recent position samples; teleport jumps reset the history.')
config = config.replace('-- Requested spectator-facing aim handling; this does not guarantee concealment.',
                        '-- Rewrites idle MOUSE updates to camera-forward; shot windows use real aim. No concealment guarantee.')
config_path.write_text(config)
(root / 'neoperro-config-updated.lua').write_text(config)
table = config.split("getgenv()['neoperro'] = ", 1)[1].strip().rstrip(';')
defaults = 'return ' + table + '\n'
(root / 'neoperro-src/defaults.lua').write_text(defaults)
core = (root / 'neoperro-src/core.lua').read_text()
intro = (root / 'neoperro-intro-preview.lua').read_text()
body = (root / 'neoperro-src/runtime.lua').read_text()
runtime = ('-- neoperro v1.0.0 | generated by build-neoperro.py\n'
           'local Core = (function()\n' + core + '\nend)()\n'
           'local Defaults = (function()\n' + defaults + '\nend)()\n'
           'local function playIntro()\n' + intro + '\nend\n' + body)
(root / 'neoperro-runtime.lua').write_text(runtime)
(root / 'neoperro.lua').write_text(config + '\n\n-- Runtime begins below.\n' + runtime)
print('Built neoperro.lua and neoperro-runtime.lua')
