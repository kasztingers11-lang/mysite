from pathlib import Path

root = Path(__file__).resolve().parent
config_path = root / 'neoperro-config.lua'
config = config_path.read_text()
table = config.split("getgenv()['neoperro'] = ", 1)[1].strip().rstrip(';')
defaults = 'return ' + table + '\n'
(root / 'neoperro-src/defaults.lua').write_text(defaults)
core = (root / 'neoperro-src/core.lua').read_text()
posture = (root / 'neoperro-src/posture.lua').read_text()
intro_path = root / 'neoperro-intro/preview.lua'
if not intro_path.exists():
    intro_path = root / 'neoperro-intro-preview.lua'
intro = intro_path.read_text()
body = (root / 'neoperro-src/runtime.lua').read_text()
runtime = ('-- neoperro v1.3.19 | generated by build-neoperro.py\n'
           'local Core = (function()\n' + core + '\nend)()\n'
           'local Posture = (function()\n' + posture + '\nend)()\n'
           'local Defaults = (function()\n' + defaults + '\nend)()\n'
           'local function playIntro()\n' + intro + '\nend\n' + body)
(root / 'neoperro-runtime.lua').write_text(runtime)
(root / 'neoperro-full.lua').write_text(config + '\n\n-- Runtime begins below.\n' + runtime)
tail = (root / 'neoperro-src/loader-tail.lua').read_text()
tail = (tail.replace('__NEOPERRO_VERSION__', '1.3.19')
        .replace('__NEOPERRO_DISTRIBUTION__', 'Development')
        .replace('__NEOPERRO_LOADER_URL__', 'https://raw.githubusercontent.com/kasztingers11-lang/mysite/repair/neoperro-evidence/neoperro-runtime.lua')
        .replace('__NEOPERRO_CLEAR_KEY__', '-- No key is used by the development loader.')
        .replace('__NEOPERRO_KEY_ARGUMENT__', 'neoperroEnvironment.neoperro'))
loader = config + '\n\n' + tail
(root / 'neoperro.lua').write_text(loader)
print('Built neoperro.lua loader, neoperro-full.lua and neoperro-runtime.lua')
